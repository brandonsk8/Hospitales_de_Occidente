-- Factura emitida al cancelar el servicio (de una cita o de un ingreso)
CREATE TABLE factura (
    id_factura     INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    numero         VARCHAR(20)    NOT NULL,
    id_hospital    SMALLINT       NOT NULL,
    id_paciente    INTEGER        NOT NULL,
    nit            VARCHAR(12)    NOT NULL DEFAULT 'CF',
    fecha_emision  TIMESTAMP      NOT NULL,
    descripcion    VARCHAR(250)   NOT NULL,
    id_cita        INTEGER,
    id_ingreso     INTEGER,
    numero_cuotas  SMALLINT       NOT NULL DEFAULT 1,
    total          NUMERIC(12,2)  NOT NULL,
    CONSTRAINT pk_factura PRIMARY KEY (id_factura),
    CONSTRAINT uq_factura_numero UNIQUE (numero),
    CONSTRAINT uq_factura_cita UNIQUE (id_cita),
    CONSTRAINT uq_factura_ingreso UNIQUE (id_ingreso),
    -- NIT numérico (con dígito verificador opcional K) o Consumidor Final
    CONSTRAINT ck_factura_nit CHECK (nit = 'CF' OR nit ~ '^[0-9]{1,11}[0-9K]$'),
    -- La factura corresponde a una cita o a un ingreso, exactamente uno
    CONSTRAINT ck_factura_origen CHECK (num_nonnulls(id_cita, id_ingreso) = 1),
    -- Pago en 1 a 12 cuotas mensuales
    CONSTRAINT ck_factura_cuotas CHECK (numero_cuotas BETWEEN 1 AND 12),
    -- La consulta externa se cancela en su totalidad (una sola cuota)
    CONSTRAINT ck_factura_cuotas_cita CHECK (id_cita IS NULL OR numero_cuotas = 1),
    -- Total no negativo
    CONSTRAINT ck_factura_total CHECK (total >= 0),
    CONSTRAINT fk_factura_hospital FOREIGN KEY (id_hospital)
        REFERENCES hospital (id_hospital)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_factura_paciente FOREIGN KEY (id_paciente)
        REFERENCES paciente (id_paciente)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_factura_cita FOREIGN KEY (id_cita)
        REFERENCES cita (id_cita)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_factura_ingreso FOREIGN KEY (id_ingreso)
        REFERENCES ficha_ingreso (id_ingreso)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Líneas de detalle de la factura (entidad débil)
CREATE TABLE detalle_factura (
    id_factura       INTEGER        NOT NULL,
    linea            SMALLINT       NOT NULL,
    concepto         VARCHAR(150)   NOT NULL,
    cantidad         NUMERIC(8,2)   NOT NULL,
    precio_unitario  NUMERIC(10,2)  NOT NULL,
    subtotal         NUMERIC(12,2)  GENERATED ALWAYS AS (ROUND(cantidad * precio_unitario, 2)) STORED,
    CONSTRAINT pk_detalle_factura PRIMARY KEY (id_factura, linea),
    -- Número de línea positivo
    CONSTRAINT ck_detalle_factura_linea CHECK (linea > 0),
    -- Cantidad positiva
    CONSTRAINT ck_detalle_factura_cantidad CHECK (cantidad > 0),
    -- Precio unitario no negativo
    CONSTRAINT ck_detalle_factura_precio CHECK (precio_unitario >= 0),
    CONSTRAINT fk_detalle_factura_factura FOREIGN KEY (id_factura)
        REFERENCES factura (id_factura)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- Cuotas mensuales de pago de una factura (entidad débil)
CREATE TABLE cuota_pago (
    id_factura         INTEGER        NOT NULL,
    numero_cuota       SMALLINT       NOT NULL,
    monto              NUMERIC(12,2)  NOT NULL,
    fecha_vencimiento  DATE           NOT NULL,
    fecha_pago         DATE,
    lugar_pago         VARCHAR(30)    NOT NULL,
    CONSTRAINT pk_cuota_pago PRIMARY KEY (id_factura, numero_cuota),
    -- Número de cuota entre 1 y 12
    CONSTRAINT ck_cuota_pago_numero CHECK (numero_cuota BETWEEN 1 AND 12),
    -- Monto de la cuota positivo
    CONSTRAINT ck_cuota_pago_monto CHECK (monto > 0),
    -- Recepción donde se realiza el pago según la unidad
    CONSTRAINT ck_cuota_pago_lugar CHECK (lugar_pago IN
        ('Recepción del médico', 'Recepción de hospitalización', 'Recepción de cirugía')),
    CONSTRAINT fk_cuota_pago_factura FOREIGN KEY (id_factura)
        REFERENCES factura (id_factura)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- Calificaciones de calidad del servicio: hospital, médico, enfermero o encargado de unidad
CREATE TABLE calificacion (
    id_calificacion        INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_hospital            SMALLINT     NOT NULL,
    tipo_calificado        VARCHAR(9)   NOT NULL,
    id_persona_calificada  INTEGER,
    id_paciente            INTEGER,
    puntuacion             SMALLINT     NOT NULL,
    comentario             VARCHAR(250),
    fecha                  DATE         NOT NULL,
    CONSTRAINT pk_calificacion PRIMARY KEY (id_calificacion),
    -- Objeto calificado
    CONSTRAINT ck_calificacion_tipo CHECK (tipo_calificado IN ('Hospital', 'Médico', 'Enfermero', 'Encargado')),
    -- Si se califica al hospital no hay persona calificada; en otro caso es obligatoria
    CONSTRAINT ck_calificacion_persona CHECK ((tipo_calificado = 'Hospital') = (id_persona_calificada IS NULL)),
    -- Puntuación de 1 a 5
    CONSTRAINT ck_calificacion_puntuacion CHECK (puntuacion BETWEEN 1 AND 5),
    CONSTRAINT fk_calificacion_hospital FOREIGN KEY (id_hospital)
        REFERENCES hospital (id_hospital)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_calificacion_persona FOREIGN KEY (id_persona_calificada)
        REFERENCES persona (id_persona)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_calificacion_paciente FOREIGN KEY (id_paciente)
        REFERENCES paciente (id_paciente)
        ON DELETE SET NULL ON UPDATE CASCADE
);

