-- Exploración física de la historia clínica (1:1)
CREATE TABLE exploracion_fisica (
    id_historia              INTEGER       NOT NULL,
    presion_sistolica        SMALLINT      NOT NULL,
    presion_diastolica       SMALLINT      NOT NULL,
    frecuencia_cardiaca      SMALLINT      NOT NULL,
    frecuencia_respiratoria  SMALLINT      NOT NULL,
    temperatura              NUMERIC(4,1)  NOT NULL,
    saturacion_o2            SMALLINT,
    exploracion_general      TEXT          NOT NULL,
    cabeza                   TEXT,
    cuello                   TEXT,
    torax                    TEXT,
    abdomen                  TEXT,
    extremidades             TEXT,
    columna_vertebral        TEXT,
    cavidades                TEXT,
    CONSTRAINT pk_exploracion_fisica PRIMARY KEY (id_historia),
    -- Presión sistólica en mmHg dentro de rango fisiológico
    CONSTRAINT ck_exploracion_fisica_sistolica CHECK (presion_sistolica BETWEEN 40 AND 300),
    -- Presión diastólica en mmHg, menor que la sistólica
    CONSTRAINT ck_exploracion_fisica_diastolica CHECK (presion_diastolica BETWEEN 20 AND 200
                                                        AND presion_diastolica < presion_sistolica),
    -- Frecuencia cardíaca (lpm)
    CONSTRAINT ck_exploracion_fisica_fc CHECK (frecuencia_cardiaca BETWEEN 20 AND 250),
    -- Frecuencia respiratoria (rpm)
    CONSTRAINT ck_exploracion_fisica_fr CHECK (frecuencia_respiratoria BETWEEN 4 AND 80),
    -- Temperatura corporal en °C
    CONSTRAINT ck_exploracion_fisica_temp CHECK (temperatura BETWEEN 30 AND 45),
    -- Saturación de oxígeno en porcentaje
    CONSTRAINT ck_exploracion_fisica_sat CHECK (saturacion_o2 BETWEEN 50 AND 100),
    CONSTRAINT fk_exploracion_fisica_historia FOREIGN KEY (id_historia)
        REFERENCES historia_clinica (id_historia)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- Agendamiento quirúrgico: solicitud del cirujano revisada por el comité médico
CREATE TABLE solicitud_cirugia (
    id_solicitud            INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_paciente             INTEGER      NOT NULL,
    edad_anios              SMALLINT     NOT NULL,
    id_historia             INTEGER      NOT NULL,
    id_cirujano             INTEGER      NOT NULL,
    id_unidad               INTEGER      NOT NULL,
    caracter                VARCHAR(10)  NOT NULL,
    tiempo_estimado_min     SMALLINT     NOT NULL,
    tipo_anestesia          VARCHAR(10)  NOT NULL,
    fecha_hora_solicitud    TIMESTAMP    NOT NULL,
    estado                  VARCHAR(9)   NOT NULL DEFAULT 'Pendiente',
    fecha_revision          DATE,
    fecha_hora_programada   TIMESTAMP,
    id_quirofano            INTEGER,
    CONSTRAINT pk_solicitud_cirugia PRIMARY KEY (id_solicitud),
    -- Edad en años dentro de rango válido
    CONSTRAINT ck_solicitud_cirugia_edad CHECK (edad_anios BETWEEN 0 AND 120),
    -- Carácter de la cirugía Urgente / Programado
    CONSTRAINT ck_solicitud_cirugia_caracter CHECK (caracter IN ('Urgente', 'Programado')),
    -- Tiempo estimado entre 1 minuto y 24 horas
    CONSTRAINT ck_solicitud_cirugia_tiempo CHECK (tiempo_estimado_min BETWEEN 1 AND 1440),
    -- Tipo de anestesia válido
    CONSTRAINT ck_solicitud_cirugia_anestesia CHECK (tipo_anestesia IN ('General', 'Regional', 'Local', 'Sedación')),
    -- Estado de la solicitud ante el comité
    CONSTRAINT ck_solicitud_cirugia_estado CHECK (estado IN ('Pendiente', 'Aprobada', 'Rechazada')),
    -- Una solicitud revisada (aprobada/rechazada) debe tener fecha de revisión
    CONSTRAINT ck_solicitud_cirugia_revision CHECK ((estado = 'Pendiente') = (fecha_revision IS NULL)),
    -- Solo una solicitud aprobada tiene fecha/hora y quirófano asignados
    CONSTRAINT ck_solicitud_cirugia_agenda CHECK (
        (estado = 'Aprobada') = (fecha_hora_programada IS NOT NULL AND id_quirofano IS NOT NULL)),
    -- Las cirugías programadas se agendan en horario matutino/vespertino (07:00-18:59)
    CONSTRAINT ck_solicitud_cirugia_horario CHECK (caracter = 'Urgente' OR fecha_hora_programada IS NULL
        OR fecha_hora_programada::TIME BETWEEN TIME '07:00' AND TIME '18:59'),
    CONSTRAINT fk_solicitud_cirugia_paciente FOREIGN KEY (id_paciente)
        REFERENCES paciente (id_paciente)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_solicitud_cirugia_historia FOREIGN KEY (id_historia)
        REFERENCES historia_clinica (id_historia)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_solicitud_cirugia_cirujano FOREIGN KEY (id_cirujano)
        REFERENCES medico (id_medico)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_solicitud_cirugia_unidad FOREIGN KEY (id_unidad)
        REFERENCES unidad_medica (id_unidad)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_solicitud_cirugia_quirofano FOREIGN KEY (id_quirofano)
        REFERENCES quirofano (id_quirofano)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

