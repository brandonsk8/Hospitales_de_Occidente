    CONSTRAINT ck_cirugia_documento_fase CHECK (fase IN ('Preoperatorio', 'Intraoperatorio', 'Postoperatorio')),
    CONSTRAINT fk_cirugia_documento_cirugia FOREIGN KEY (id_cirugia)
        REFERENCES cirugia (id_cirugia)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_cirugia_documento_enfermero FOREIGN KEY (id_enfermero)
        REFERENCES enfermero (id_enfermero)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Insumos consumidos durante un ingreso (cirugía u hospitalización), base del cobro
CREATE TABLE consumo_insumo (
