-- Catálogo de medicamentos
CREATE TABLE medicamento (
    id_medicamento  INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR(80)  NOT NULL,
    presentacion    VARCHAR(60)  NOT NULL,
    CONSTRAINT pk_medicamento PRIMARY KEY (id_medicamento),
    CONSTRAINT uq_medicamento_nombre_pres UNIQUE (nombre, presentacion)
);

-- Ficha de cita programada de Consulta externa (con control de estado y costo)
CREATE TABLE cita (
    id_cita                  INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    id_paciente              INTEGER        NOT NULL,
    id_medico                INTEGER        NOT NULL,
    id_clinica               INTEGER        NOT NULL,
    fecha_hora               TIMESTAMP      NOT NULL,
    medio_solicitud          VARCHAR(20)    NOT NULL,
    tipo_cita                VARCHAR(16)    NOT NULL,
    es_referido              BOOLEAN        NOT NULL DEFAULT FALSE,
    id_hospital_referente    SMALLINT,
    estado                   VARCHAR(12)    NOT NULL DEFAULT 'Programada',
    cancelacion_notificada   BOOLEAN,
    id_cita_anterior         INTEGER,
    costo_base               NUMERIC(10,2)  NOT NULL,
    porcentaje_costo         NUMERIC(5,2)   NOT NULL,
    recargo_cancelacion      BOOLEAN        NOT NULL DEFAULT FALSE,
    costo_total              NUMERIC(10,2)  GENERATED ALWAYS AS (
        ROUND(costo_base * porcentaje_costo / 100
              * CASE WHEN recargo_cancelacion THEN 1.10 ELSE 1 END, 2)) STORED,
    CONSTRAINT pk_cita PRIMARY KEY (id_cita),
    -- Medio por el que se solicitó la cita
    CONSTRAINT ck_cita_medio CHECK (medio_solicitud IN ('Teléfono', 'Correo', 'Recepción general')),
    -- Primera consulta o reconsulta
    CONSTRAINT ck_cita_tipo CHECK (tipo_cita IN ('Primera consulta', 'Reconsulta')),
    -- Estado de la cita
    CONSTRAINT ck_cita_estado CHECK (estado IN ('Programada', 'Realizada', 'Reprogramada', 'Cancelada')),
    -- Consulta externa solo en turno matutino (06:00 a 12:59)
    CONSTRAINT ck_cita_horario CHECK (fecha_hora::TIME BETWEEN TIME '06:00' AND TIME '12:59'),
    -- Si es referido debe indicarse la institución que refiere, y viceversa
    CONSTRAINT ck_cita_referido CHECK (es_referido = (id_hospital_referente IS NOT NULL)),
    -- Solo las citas canceladas indican si la cancelación fue notificada
    CONSTRAINT ck_cita_cancelacion CHECK ((estado = 'Cancelada') = (cancelacion_notificada IS NOT NULL)),
    -- Costo base positivo
    CONSTRAINT ck_cita_costo_base CHECK (costo_base > 0),
    -- Porcentaje: 80% referido, 75% reconsulta, 100% primera consulta
    CONSTRAINT ck_cita_porcentaje CHECK (porcentaje_costo =
        CASE WHEN es_referido THEN 80 WHEN tipo_cita = 'Reconsulta' THEN 75 ELSE 100 END),
    -- Una cita no puede referenciarse a sí misma
    CONSTRAINT ck_cita_anterior CHECK (id_cita_anterior <> id_cita),
    CONSTRAINT fk_cita_paciente FOREIGN KEY (id_paciente)
        REFERENCES paciente (id_paciente)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_cita_medico FOREIGN KEY (id_medico)
        REFERENCES medico (id_medico)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_cita_clinica FOREIGN KEY (id_clinica)
        REFERENCES clinica (id_clinica)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_cita_hospital_referente FOREIGN KEY (id_hospital_referente)
        REFERENCES hospital (id_hospital)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_cita_cita_anterior FOREIGN KEY (id_cita_anterior)
        REFERENCES cita (id_cita)
        ON DELETE SET NULL ON UPDATE CASCADE
);

-- Ficha de consulta del paciente: registro de la consulta realizada (1:1 con cita)
CREATE TABLE consulta (
    id_consulta    INTEGER    GENERATED BY DEFAULT AS IDENTITY,
    id_cita        INTEGER    NOT NULL,
    fecha_hora     TIMESTAMP  NOT NULL,
    diagnostico    TEXT       NOT NULL,
    orientacion    TEXT,
    otros_datos    TEXT,
    observaciones  TEXT,
    CONSTRAINT pk_consulta PRIMARY KEY (id_consulta),
    CONSTRAINT uq_consulta_cita UNIQUE (id_cita),
    CONSTRAINT fk_consulta_cita FOREIGN KEY (id_cita)
        REFERENCES cita (id_cita)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Receta médica emitida en una consulta
CREATE TABLE receta (
    id_receta           INTEGER  GENERATED BY DEFAULT AS IDENTITY,
    id_consulta         INTEGER  NOT NULL,
    fecha               DATE     NOT NULL,
    fecha_proxima_cita  DATE,
    CONSTRAINT pk_receta PRIMARY KEY (id_receta),
    -- La próxima cita debe ser posterior a la fecha de la receta
    CONSTRAINT ck_receta_proxima_cita CHECK (fecha_proxima_cita > fecha),
    CONSTRAINT fk_receta_consulta FOREIGN KEY (id_consulta)
        REFERENCES consulta (id_consulta)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- Asociativa receta-medicamento (M:N): prescripción con dosis y duración
CREATE TABLE receta_medicamento (
    id_receta       INTEGER       NOT NULL,
    id_medicamento  INTEGER       NOT NULL,
    dosis           VARCHAR(100)  NOT NULL,
    duracion        VARCHAR(50)   NOT NULL,
    CONSTRAINT pk_receta_medicamento PRIMARY KEY (id_receta, id_medicamento),
    CONSTRAINT fk_receta_medicamento_receta FOREIGN KEY (id_receta)
        REFERENCES receta (id_receta)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_receta_medicamento_medicamento FOREIGN KEY (id_medicamento)
        REFERENCES medicamento (id_medicamento)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Órdenes de laboratorio emitidas en una consulta
CREATE TABLE orden_laboratorio (
    id_orden      INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    id_consulta   INTEGER       NOT NULL,
    examen        VARCHAR(100)  NOT NULL,
    indicaciones  VARCHAR(250),
    CONSTRAINT pk_orden_laboratorio PRIMARY KEY (id_orden),
    CONSTRAINT fk_orden_laboratorio_consulta FOREIGN KEY (id_consulta)
        REFERENCES consulta (id_consulta)
        ON DELETE CASCADE ON UPDATE CASCADE
);

