-- =====================================================================
-- Modelado y Gestión de una Base de Datos Hospitalaria
-- DDL: definición de la base de datos "hospitales_occidente"
-- SGBD: PostgreSQL 16+
--
-- Uso:
--   psql -U postgres -c "CREATE DATABASE hospitales_occidente ENCODING 'UTF8';"
--   psql -U postgres -d hospitales_occidente -f 01_ddl.sql
--
-- Convenciones de nombres:
--   pk_<tabla>, fk_<tabla>_<referencia>, uq_<tabla>_<campos>, ck_<tabla>_<regla>
-- La justificación de cada acción referencial está en el diccionario de datos (PDF).
-- =====================================================================

DROP SCHEMA IF EXISTS hospital CASCADE;
CREATE SCHEMA hospital;
SET search_path TO hospital;

-- =====================================================================
-- 1. UBICACIÓN GEOGRÁFICA
-- =====================================================================

-- Departamentos de Guatemala (catálogo)
CREATE TABLE departamento (
    id_departamento  SMALLINT     GENERATED BY DEFAULT AS IDENTITY,
    nombre           VARCHAR(50)  NOT NULL,
    CONSTRAINT pk_departamento PRIMARY KEY (id_departamento),
    CONSTRAINT uq_departamento_nombre UNIQUE (nombre)
);

-- Municipios de cada departamento (catálogo)
CREATE TABLE municipio (
    id_municipio     INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_departamento  SMALLINT     NOT NULL,
    nombre           VARCHAR(60)  NOT NULL,
    CONSTRAINT pk_municipio PRIMARY KEY (id_municipio),
    CONSTRAINT uq_municipio_depto_nombre UNIQUE (id_departamento, nombre),
    CONSTRAINT fk_municipio_departamento FOREIGN KEY (id_departamento)
        REFERENCES departamento (id_departamento)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- =====================================================================
-- 2. PERSONAS (supertipo) Y SUBTIPOS
-- =====================================================================

-- Datos comunes de toda persona: pacientes, encargados, médicos y enfermeros
CREATE TABLE persona (
    id_persona        INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    nombres           VARCHAR(80)   NOT NULL,
    apellidos         VARCHAR(80)   NOT NULL,
    dpi               CHAR(13),
    fecha_nacimiento  DATE          NOT NULL,
    sexo              VARCHAR(9)    NOT NULL,
    estado_civil      VARCHAR(12),
    telefono          VARCHAR(8),
    direccion         VARCHAR(150),
    id_municipio      INTEGER       NOT NULL,
    area              VARCHAR(6)    NOT NULL,
    CONSTRAINT pk_persona PRIMARY KEY (id_persona),
    CONSTRAINT uq_persona_dpi UNIQUE (dpi),
    -- DPI: exactamente 13 dígitos numéricos
    CONSTRAINT ck_persona_dpi CHECK (dpi ~ '^[0-9]{13}$'),
    -- Sexo limitado a Masculino / Femenino
    CONSTRAINT ck_persona_sexo CHECK (sexo IN ('Masculino', 'Femenino')),
    -- Estado civil con valores válidos
    CONSTRAINT ck_persona_estado_civil CHECK (estado_civil IN ('Soltero', 'Casado', 'Unido', 'Divorciado', 'Viudo')),
    -- Teléfono guatemalteco de 8 dígitos
    CONSTRAINT ck_persona_telefono CHECK (telefono ~ '^[0-9]{8}$'),
    -- Área de residencia Urbana / Rural
    CONSTRAINT ck_persona_area CHECK (area IN ('Urbana', 'Rural')),
    -- Fecha de nacimiento dentro de un rango razonable
    CONSTRAINT ck_persona_fecha_nac CHECK (fecha_nacimiento >= DATE '1900-01-01'),
    CONSTRAINT fk_persona_municipio FOREIGN KEY (id_municipio)
        REFERENCES municipio (id_municipio)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Subtipo de persona: paciente atendido en algún hospital de la cadena
CREATE TABLE paciente (
    id_paciente        INTEGER      NOT NULL,
    no_expediente      VARCHAR(20)  NOT NULL,
    no_seguro_social   VARCHAR(20),
    fecha_registro     DATE         NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT pk_paciente PRIMARY KEY (id_paciente),
    CONSTRAINT uq_paciente_expediente UNIQUE (no_expediente),
    CONSTRAINT uq_paciente_seguro UNIQUE (no_seguro_social),
    CONSTRAINT fk_paciente_persona FOREIGN KEY (id_paciente)
        REFERENCES persona (id_persona)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- Asociativa paciente-encargado (M:N): responsables de cada paciente
CREATE TABLE paciente_encargado (
    id_paciente   INTEGER      NOT NULL,
    id_encargado  INTEGER      NOT NULL,
    parentesco    VARCHAR(20)  NOT NULL,
    CONSTRAINT pk_paciente_encargado PRIMARY KEY (id_paciente, id_encargado),
    -- Parentesco con valores válidos
    CONSTRAINT ck_paciente_encargado_parentesco CHECK (parentesco IN
        ('Padre', 'Madre', 'Hijo', 'Hija', 'Cónyuge', 'Hermano', 'Hermana',
         'Abuelo', 'Abuela', 'Tío', 'Tía', 'Tutor legal', 'Otro')),
    -- Un paciente no puede ser su propio encargado
    CONSTRAINT ck_paciente_encargado_distinto CHECK (id_paciente <> id_encargado),
    CONSTRAINT fk_paciente_encargado_paciente FOREIGN KEY (id_paciente)
        REFERENCES paciente (id_paciente)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_paciente_encargado_persona FOREIGN KEY (id_encargado)
        REFERENCES persona (id_persona)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Catálogo de especialidades médicas
CREATE TABLE especialidad (
    id_especialidad  SMALLINT     GENERATED BY DEFAULT AS IDENTITY,
    nombre           VARCHAR(60)  NOT NULL,
    CONSTRAINT pk_especialidad PRIMARY KEY (id_especialidad),
    CONSTRAINT uq_especialidad_nombre UNIQUE (nombre)
);

-- Subtipo de persona: médico (residente, interno, externo o practicante)
CREATE TABLE medico (
    id_medico           INTEGER        NOT NULL,
    no_colegiado        VARCHAR(10),
    tipo_medico         VARCHAR(11)    NOT NULL,
    institucion_origen  VARCHAR(100),
    costo_consulta      NUMERIC(10,2),
    CONSTRAINT pk_medico PRIMARY KEY (id_medico),
    CONSTRAINT uq_medico_colegiado UNIQUE (no_colegiado),
    -- Tipo de médico según su vínculo con el hospital
    CONSTRAINT ck_medico_tipo CHECK (tipo_medico IN ('Residente', 'Interno', 'Externo', 'Practicante')),
    -- Solo el practicante puede no tener número de colegiado
    CONSTRAINT ck_medico_colegiado CHECK (tipo_medico = 'Practicante' OR no_colegiado IS NOT NULL),
    -- La institución de origen es obligatoria solo para médicos externos
    CONSTRAINT ck_medico_externo CHECK ((tipo_medico = 'Externo') = (institucion_origen IS NOT NULL)),
    -- El costo de consulta debe ser positivo
    CONSTRAINT ck_medico_costo CHECK (costo_consulta > 0),
    CONSTRAINT fk_medico_persona FOREIGN KEY (id_medico)
        REFERENCES persona (id_persona)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- Asociativa médico-especialidad (M:N)
CREATE TABLE medico_especialidad (
    id_medico        INTEGER   NOT NULL,
    id_especialidad  SMALLINT  NOT NULL,
    CONSTRAINT pk_medico_especialidad PRIMARY KEY (id_medico, id_especialidad),
    CONSTRAINT fk_medico_especialidad_medico FOREIGN KEY (id_medico)
        REFERENCES medico (id_medico)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_medico_especialidad_especialidad FOREIGN KEY (id_especialidad)
        REFERENCES especialidad (id_especialidad)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Subtipo de persona: enfermero registrado o practicante de enfermería
CREATE TABLE enfermero (
    id_enfermero    INTEGER      NOT NULL,
    no_registro     VARCHAR(10),
    tipo_enfermero  VARCHAR(11)  NOT NULL,
    CONSTRAINT pk_enfermero PRIMARY KEY (id_enfermero),
    CONSTRAINT uq_enfermero_registro UNIQUE (no_registro),
    -- Tipo de enfermero Registrado / Practicante
    CONSTRAINT ck_enfermero_tipo CHECK (tipo_enfermero IN ('Registrado', 'Practicante')),
    -- El enfermero registrado debe tener número de registro
    CONSTRAINT ck_enfermero_registro CHECK (tipo_enfermero = 'Practicante' OR no_registro IS NOT NULL),
    CONSTRAINT fk_enfermero_persona FOREIGN KEY (id_enfermero)
        REFERENCES persona (id_persona)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- =====================================================================
-- 3. HOSPITALES, UNIDADES, SERVICIOS Y RECURSOS FÍSICOS
-- =====================================================================

-- Hospitales de la cadena y establecimientos externos (para traslados/referencias)
CREATE TABLE hospital (
    id_hospital            SMALLINT      GENERATED BY DEFAULT AS IDENTITY,
    nombre                 VARCHAR(100)  NOT NULL,
    descripcion            VARCHAR(250),
    direccion              VARCHAR(150)  NOT NULL,
    id_municipio           INTEGER       NOT NULL,
    telefono               VARCHAR(8),
    pertenece_institucion  BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_hospital PRIMARY KEY (id_hospital),
    CONSTRAINT uq_hospital_nombre UNIQUE (nombre),
    -- Teléfono de 8 dígitos
    CONSTRAINT ck_hospital_telefono CHECK (telefono ~ '^[0-9]{8}$'),
    CONSTRAINT fk_hospital_municipio FOREIGN KEY (id_municipio)
        REFERENCES municipio (id_municipio)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Unidades médicas de cada hospital (Consulta externa, Emergencias, Cirugía, Hospitalización, Otro)
CREATE TABLE unidad_medica (
    id_unidad      INTEGER        GENERATED BY DEFAULT AS IDENTITY,
    id_hospital    SMALLINT       NOT NULL,
    tipo_unidad    VARCHAR(17)    NOT NULL,
    telefono       VARCHAR(8),
    costo_dia      NUMERIC(10,2),
    CONSTRAINT pk_unidad_medica PRIMARY KEY (id_unidad),
    CONSTRAINT uq_unidad_medica_hosp_tipo UNIQUE (id_hospital, tipo_unidad),
    -- Tipo de unidad médica válido
    CONSTRAINT ck_unidad_medica_tipo CHECK (tipo_unidad IN
        ('Consulta externa', 'Emergencias', 'Cirugía', 'Hospitalización', 'Otro')),
    -- Teléfono de 8 dígitos
    CONSTRAINT ck_unidad_medica_telefono CHECK (telefono ~ '^[0-9]{8}$'),
    -- Costo por día solo aplica (y es no negativo) en Hospitalización
    CONSTRAINT ck_unidad_medica_costo_dia CHECK (costo_dia IS NULL OR (tipo_unidad = 'Hospitalización' AND costo_dia >= 0)),
    CONSTRAINT fk_unidad_medica_hospital FOREIGN KEY (id_hospital)
        REFERENCES hospital (id_hospital)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- Catálogo de servicios / tipos de atención médica, clasificados por tipo de unidad
CREATE TABLE servicio (
    id_servicio  SMALLINT      GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR(80)   NOT NULL,
    tipo_unidad  VARCHAR(17)   NOT NULL,
    CONSTRAINT pk_servicio PRIMARY KEY (id_servicio),
    CONSTRAINT uq_servicio_nombre_tipo UNIQUE (nombre, tipo_unidad),
    -- Tipo de unidad a la que pertenece el servicio
    CONSTRAINT ck_servicio_tipo_unidad CHECK (tipo_unidad IN
        ('Consulta externa', 'Emergencias', 'Cirugía', 'Hospitalización', 'Otro'))
);

-- Asociativa unidad-servicio (M:N): servicios ofrecidos por cada unidad y su costo
CREATE TABLE unidad_servicio (
    id_unidad    INTEGER        NOT NULL,
    id_servicio  SMALLINT       NOT NULL,
    costo        NUMERIC(10,2)  NOT NULL,
    CONSTRAINT pk_unidad_servicio PRIMARY KEY (id_unidad, id_servicio),
    -- El costo del servicio no puede ser negativo
    CONSTRAINT ck_unidad_servicio_costo CHECK (costo >= 0),
    CONSTRAINT fk_unidad_servicio_unidad FOREIGN KEY (id_unidad)
        REFERENCES unidad_medica (id_unidad)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_unidad_servicio_servicio FOREIGN KEY (id_servicio)
        REFERENCES servicio (id_servicio)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Asociativa médico-unidad (M:N): asignación laboral de médicos a unidades
CREATE TABLE medico_unidad (
    id_medico     INTEGER      NOT NULL,
    id_unidad     INTEGER      NOT NULL,
    fecha_inicio  DATE         NOT NULL,
    jornada       VARCHAR(11)  NOT NULL,
    es_jefe       BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_medico_unidad PRIMARY KEY (id_medico, id_unidad),
    -- Jornada laboral válida
    CONSTRAINT ck_medico_unidad_jornada CHECK (jornada IN
        ('Matutina', 'Vespertina', 'Mixta', 'Por turnos', 'Por llamado')),
    CONSTRAINT fk_medico_unidad_medico FOREIGN KEY (id_medico)
        REFERENCES medico (id_medico)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_medico_unidad_unidad FOREIGN KEY (id_unidad)
        REFERENCES unidad_medica (id_unidad)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- Asociativa enfermero-unidad (M:N): asignación laboral de enfermeros a unidades
CREATE TABLE enfermero_unidad (
    id_enfermero  INTEGER      NOT NULL,
    id_unidad     INTEGER      NOT NULL,
    fecha_inicio  DATE         NOT NULL,
    jornada       VARCHAR(11)  NOT NULL,
    es_jefe       BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_enfermero_unidad PRIMARY KEY (id_enfermero, id_unidad),
    -- Jornada laboral válida
    CONSTRAINT ck_enfermero_unidad_jornada CHECK (jornada IN
        ('Matutina', 'Vespertina', 'Mixta', 'Por turnos', 'Por llamado')),
    CONSTRAINT fk_enfermero_unidad_enfermero FOREIGN KEY (id_enfermero)
        REFERENCES enfermero (id_enfermero)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_enfermero_unidad_unidad FOREIGN KEY (id_unidad)
        REFERENCES unidad_medica (id_unidad)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- Turnos de 12 horas de la unidad de Emergencias
CREATE TABLE turno_emergencia (
    id_turno   INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    id_unidad  INTEGER     NOT NULL,
    fecha      DATE        NOT NULL,
    jornada    VARCHAR(8)  NOT NULL,
    CONSTRAINT pk_turno_emergencia PRIMARY KEY (id_turno),
    CONSTRAINT uq_turno_emergencia UNIQUE (id_unidad, fecha, jornada),
    -- Turnos de 12 h: Diurno (07:00-19:00) o Nocturno (19:00-07:00)
    CONSTRAINT ck_turno_emergencia_jornada CHECK (jornada IN ('Diurno', 'Nocturno')),
    CONSTRAINT fk_turno_emergencia_unidad FOREIGN KEY (id_unidad)
        REFERENCES unidad_medica (id_unidad)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- Asociativa turno-médico (M:N): médicos que cubren cada turno de emergencia
CREATE TABLE turno_medico (
    id_turno   INTEGER  NOT NULL,
    id_medico  INTEGER  NOT NULL,
    CONSTRAINT pk_turno_medico PRIMARY KEY (id_turno, id_medico),
    CONSTRAINT fk_turno_medico_turno FOREIGN KEY (id_turno)
        REFERENCES turno_emergencia (id_turno)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_turno_medico_medico FOREIGN KEY (id_medico)
        REFERENCES medico (id_medico)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Clínicas / consultorios de la Consulta externa
CREATE TABLE clinica (
    id_clinica  INTEGER   GENERATED BY DEFAULT AS IDENTITY,
    id_unidad   INTEGER   NOT NULL,
    numero      SMALLINT  NOT NULL,
    CONSTRAINT pk_clinica PRIMARY KEY (id_clinica),
    CONSTRAINT uq_clinica_unidad_numero UNIQUE (id_unidad, numero),
    -- Número de clínica positivo
    CONSTRAINT ck_clinica_numero CHECK (numero > 0),
    CONSTRAINT fk_clinica_unidad FOREIGN KEY (id_unidad)
        REFERENCES unidad_medica (id_unidad)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- Camillas de Emergencias y Hospitalización
CREATE TABLE camilla (
    id_camilla  INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_unidad   INTEGER      NOT NULL,
    codigo      VARCHAR(10)  NOT NULL,
    estado      VARCHAR(13)  NOT NULL DEFAULT 'Disponible',
    CONSTRAINT pk_camilla PRIMARY KEY (id_camilla),
    CONSTRAINT uq_camilla_unidad_codigo UNIQUE (id_unidad, codigo),
    -- Estado operativo de la camilla
    CONSTRAINT ck_camilla_estado CHECK (estado IN ('Disponible', 'Ocupada', 'Mantenimiento', 'Inactiva')),
    CONSTRAINT fk_camilla_unidad FOREIGN KEY (id_unidad)
        REFERENCES unidad_medica (id_unidad)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- Quirófanos (pabellones) de la unidad de Cirugía: 4 por hospital
CREATE TABLE quirofano (
    id_quirofano  INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_unidad     INTEGER      NOT NULL,
    numero        SMALLINT     NOT NULL,
    estado        VARCHAR(13)  NOT NULL DEFAULT 'Disponible',
    CONSTRAINT pk_quirofano PRIMARY KEY (id_quirofano),
    CONSTRAINT uq_quirofano_unidad_numero UNIQUE (id_unidad, numero),
    -- Cada unidad de Cirugía tiene cuatro quirófanos (1 a 4)
    CONSTRAINT ck_quirofano_numero CHECK (numero BETWEEN 1 AND 4),
    -- Estado operativo del quirófano
    CONSTRAINT ck_quirofano_estado CHECK (estado IN ('Disponible', 'Ocupado', 'Mantenimiento', 'Inactivo')),
    CONSTRAINT fk_quirofano_unidad FOREIGN KEY (id_unidad)
        REFERENCES unidad_medica (id_unidad)
        ON DELETE CASCADE ON UPDATE CASCADE
);

