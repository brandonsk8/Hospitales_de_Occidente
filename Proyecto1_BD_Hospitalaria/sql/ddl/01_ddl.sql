        REFERENCES medico (id_medico)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_chequeo_preanestesico_anestesista FOREIGN KEY (id_anestesista)
        REFERENCES medico (id_medico)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Cirugía aprobada y su ejecución (1:1 con solicitud aprobada)
CREATE TABLE cirugia (
    id_cirugia              INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_solicitud            INTEGER      NOT NULL,
    id_quirofano            INTEGER      NOT NULL,
    id_ingreso              INTEGER,
    id_enfermero_encargado  INTEGER      NOT NULL,
    estado                  VARCHAR(10)  NOT NULL DEFAULT 'Programada',
    fecha_hora_inicio       TIMESTAMP,
    fecha_hora_fin          TIMESTAMP,
    condicion_evolucion     VARCHAR(22),
    CONSTRAINT pk_cirugia PRIMARY KEY (id_cirugia),
    CONSTRAINT uq_cirugia_solicitud UNIQUE (id_solicitud),
    CONSTRAINT uq_cirugia_ingreso UNIQUE (id_ingreso),
    -- Estado de la cirugía
    CONSTRAINT ck_cirugia_estado CHECK (estado IN ('Programada', 'En curso', 'Finalizada', 'Suspendida')),
    -- La hora de fin debe ser posterior a la de inicio
    CONSTRAINT ck_cirugia_fechas CHECK (fecha_hora_fin > fecha_hora_inicio),
    -- Una cirugía finalizada debe tener hora de inicio y de fin
    CONSTRAINT ck_cirugia_finalizada CHECK (estado <> 'Finalizada'
        OR (fecha_hora_inicio IS NOT NULL AND fecha_hora_fin IS NOT NULL)),
    -- Condición de evolución durante la cirugía
    CONSTRAINT ck_cirugia_condicion CHECK (condicion_evolucion IN
        ('Sin complicaciones', 'Complicaciones', 'Complicaciones graves')),
    CONSTRAINT fk_cirugia_solicitud FOREIGN KEY (id_solicitud)
        REFERENCES solicitud_cirugia (id_solicitud)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_cirugia_quirofano FOREIGN KEY (id_quirofano)
        REFERENCES quirofano (id_quirofano)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_cirugia_ingreso FOREIGN KEY (id_ingreso)
        REFERENCES ficha_ingreso (id_ingreso)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_cirugia_enfermero FOREIGN KEY (id_enfermero_encargado)
        REFERENCES enfermero (id_enfermero)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Asociativa cirugía-persona (M:N): equipo de salud que participa en la cirugía
CREATE TABLE cirugia_personal (
    id_cirugia  INTEGER      NOT NULL,
    id_persona  INTEGER      NOT NULL,
    rol         VARCHAR(30)  NOT NULL,
    CONSTRAINT pk_cirugia_personal PRIMARY KEY (id_cirugia, id_persona),
    -- Rol dentro del equipo quirúrgico
    CONSTRAINT ck_cirugia_personal_rol CHECK (rol IN
        ('Cirujano principal', 'Cirujano asistente', 'Anestesiólogo', 'Enfermero instrumentista',
         'Enfermero circulante', 'Practicante de medicina', 'Practicante de enfermería')),
    CONSTRAINT fk_cirugia_personal_cirugia FOREIGN KEY (id_cirugia)
        REFERENCES cirugia (id_cirugia)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_cirugia_personal_persona FOREIGN KEY (id_persona)
        REFERENCES persona (id_persona)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Catálogo de aspectos a verificar en cada etapa del proceso quirúrgico
CREATE TABLE item_verificacion (
    id_item         SMALLINT      GENERATED BY DEFAULT AS IDENTITY,
    fase            VARCHAR(15)   NOT NULL,
    etapa           VARCHAR(40)   NOT NULL,
    descripcion     VARCHAR(200)  NOT NULL,
    tipo_resultado  VARCHAR(11)   NOT NULL,
    CONSTRAINT pk_item_verificacion PRIMARY KEY (id_item),
    CONSTRAINT uq_item_verificacion_etapa_desc UNIQUE (etapa, descripcion),
    CONSTRAINT uq_item_verificacion_item_tipo UNIQUE (id_item, tipo_resultado),
    -- Fase del proceso quirúrgico
    CONSTRAINT ck_item_verificacion_fase CHECK (fase IN ('Preoperatorio', 'Intraoperatorio', 'Postoperatorio')),
    -- Etapa del proceso quirúrgico
    CONSTRAINT ck_item_verificacion_etapa CHECK (etapa IN
        ('Planificación', 'Entrada', 'Chequeo en quirófano', 'Pausa quirúrgica',
         'Cuidados intraoperatorios', 'Salida quirúrgica',
         'Ingreso a sala de recuperación', 'Traslado seguro')),
    -- Forma de evaluar el aspecto: éxito/fallo o valoración de aceptabilidad
    CONSTRAINT ck_item_verificacion_tipo CHECK (tipo_resultado IN ('Éxito/Fallo', 'Valoración'))
);

-- Registro del resultado de cada aspecto verificado en una cirugía
CREATE TABLE registro_verificacion (
    id_cirugia      INTEGER       NOT NULL,
    id_item         SMALLINT      NOT NULL,
    tipo_resultado  VARCHAR(11)   NOT NULL,
    resultado       VARCHAR(22)   NOT NULL,
    fecha_hora      TIMESTAMP     NOT NULL,
    descripcion     VARCHAR(250),
    id_enfermero    INTEGER       NOT NULL,
    CONSTRAINT pk_registro_verificacion PRIMARY KEY (id_cirugia, id_item),
    -- El resultado debe corresponder al tipo de evaluación del aspecto
    CONSTRAINT ck_registro_verificacion_resultado CHECK (
        (tipo_resultado = 'Éxito/Fallo' AND resultado IN ('Éxito', 'Fallo'))
        OR (tipo_resultado = 'Valoración' AND resultado IN ('Aceptable', 'Medianamente aceptable', 'No aceptable'))),
    CONSTRAINT fk_registro_verificacion_cirugia FOREIGN KEY (id_cirugia)
        REFERENCES cirugia (id_cirugia)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_registro_verificacion_item FOREIGN KEY (id_item, tipo_resultado)
        REFERENCES item_verificacion (id_item, tipo_resultado)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_registro_verificacion_enfermero FOREIGN KEY (id_enfermero)
        REFERENCES enfermero (id_enfermero)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Documentación de cada fase de la cirugía enviada a secretaría
CREATE TABLE cirugia_documento (
